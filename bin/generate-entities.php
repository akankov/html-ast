#!/usr/bin/env php
<?php

/**
 * Regenerates src/Internal/Tokenizer/NamedCharacterReferences.php from the
 * vendored WHATWG named-character-reference data.
 *
 * Usage:
 *   php bin/generate-entities.php
 *
 * Source of truth: resources/entities.json, downloaded verbatim from
 * https://html.spec.whatwg.org/entities.json (Public Domain spec data).
 * Re-download and re-run only when the spec data changes — the WHATWG list
 * is frozen by policy, so in practice this is a one-time generation.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$jsonPath = $root . '/resources/entities.json';
$targetPath = $root . '/src/Internal/Tokenizer/NamedCharacterReferences.php';

$raw = file_get_contents($jsonPath);
if ($raw === false) {
    fwrite(STDERR, "cannot read {$jsonPath}\n");
    exit(1);
}

/** @var array<string, array{codepoints: list<int>, characters: string}> $data */
$data = json_decode($raw, true, 8, JSON_THROW_ON_ERROR);

// Deterministic output regardless of upstream key order.
ksort($data, SORT_STRING);

/**
 * Emit a PHP string literal for a decoded entity value. Values that are pure
 * printable ASCII stay single-quoted; everything else becomes a double-quoted
 * `"\u{…}"` escape sequence built from the spec's own codepoint list, so the
 * generated file is ASCII-only (no invisible characters in source — matching
 * PHP-CS-Fixer's non_printable_character rule) and regeneration is
 * byte-stable.
 *
 * @param list<int> $codepoints
 */
function phpStringLiteral(string $characters, array $codepoints): string
{
    $isPrintableAscii = true;
    foreach ($codepoints as $cp) {
        if ($cp < 0x20 || $cp > 0x7E) {
            $isPrintableAscii = false;
            break;
        }
    }

    if ($isPrintableAscii) {
        return var_export($characters, true);
    }

    $escapes = array_map(static fn (int $cp): string => sprintf('\u{%x}', $cp), $codepoints);

    return '"' . implode('', $escapes) . '"';
}

$minLength = PHP_INT_MAX;
$maxLength = 0;
$lines = [];
foreach ($data as $name => $entry) {
    $length = strlen($name);
    $minLength = min($minLength, $length);
    $maxLength = max($maxLength, $length);
    $lines[] = '        ' . var_export($name, true) . ' => ' . phpStringLiteral($entry['characters'], $entry['codepoints']) . ',';
}

$count = count($data);
$sha256 = hash('sha256', $raw);
$table = implode("\n", $lines);

$code = <<<PHP
<?php

declare(strict_types=1);

namespace Akankov\\HtmlAst\\Internal\\Tokenizer;

/**
 * The full WHATWG named-character-reference table ({$count} entries).
 *
 * @generated by bin/generate-entities.php — do not edit by hand.
 *
 * Source: resources/entities.json (https://html.spec.whatwg.org/entities.json,
 * Public Domain spec data; sha256 {$sha256}).
 *
 * Keys include the leading `&`; entries without a trailing `;` are the
 * spec's legacy named references (matching is longest-match, see
 * {@see CharacterReference::matchNamed()}).
 *
 * @internal no BC guarantees
 */
final class NamedCharacterReferences
{
    /**
     * Shortest table key in bytes (including the leading `&`).
     */
    public const int MIN_LENGTH = {$minLength};

    /**
     * Longest table key in bytes (including the leading `&` and the `;`).
     */
    public const int MAX_LENGTH = {$maxLength};

    /**
     * @var array<string, string> name → decoded UTF-8 value
     */
    public const array TABLE = [
{$table}
    ];
}

PHP;

file_put_contents($targetPath, $code);
echo "wrote {$targetPath}: {$count} entries, name length {$minLength}–{$maxLength}\n";
